/// 剪切板类型（UTI）的名字。用字符串而不用 NSPasteboard.PasteboardType，MochiCore 不依赖 AppKit。
public enum PasteboardTypes {
    public static let plainText = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"

    public static let images = [png, tiff, jpeg, heic]

    /// 读剪切板时要读数据的类型。其余类型只看名字、不读数据：有的应用要等读的时候才生成数据，
    /// 可能很慢也很大，比如 Safari 的网页存档（`com.apple.webarchive`）能有几十 MB。
    public static let captured = [plainText, rtf, html, url, fileURL] + images

    /// 文本条目除了纯文本还存这几种，粘贴时原样写回，保留格式。
    public static let textFormats = [rtf, html, url]

    /// 带了这些类型就不记录，也不读数据。前三个是 nspasteboard.org 的约定（密码、临时内容、程序自动生成的），
    /// `com.apple.is-sensitive` 是系统的，其余是 Maccy 默认忽略的几个应用自己的类型。
    public static let skipMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.apple.is-sensitive",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]
}
